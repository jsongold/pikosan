-- Café Index Tokyo catalog.
-- Extensible like the source catalog: identity lives on shops; every other
-- fact is an EAV row in shop_attributes (value jsonb + confidence + sources).
-- attribute_definitions holds labels, display_order, and optional metadata
-- (score_scale / allowed_values / atmos). A row is a taste/atmosphere axis
-- only when is_axis is true — flavor.evidence and flavor.confidence are not.
-- Event type labels use category = 'event_type'.
--
-- reviews.review_date is text so month precision ('2026-10') is kept.
-- events.starts_at / ends_at are timestamptz instants. The app formats them
-- in Asia/Tokyo; do not rely on the database TimeZone setting. all_day
-- events print the Tokyo calendar date and no clock.
--
-- anon and authenticated may SELECT only. INSERT/UPDATE/DELETE/TRUNCATE/
-- REFERENCES/TRIGGER are revoked. service_role bypasses RLS — use that key
-- only as a server-side build secret, never as NEXT_PUBLIC_.

create table public.shops (
  id bigint generated by default as identity primary key,
  name text not null,
  name_kana text,
  uid text,
  region_key text,
  prefecture text,
  ward text,
  address text,
  lat double precision,
  lng double precision,
  status text not null default 'active',
  source_urls jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint shops_lat_chk check (lat is null or (lat >= -90 and lat <= 90)),
  constraint shops_lng_chk check (lng is null or (lng >= -180 and lng <= 180))
);

create table public.attribute_definitions (
  key text primary key,
  label_ja text not null,
  category text,
  display_order integer not null default 999,
  -- Rating axes only. Non-axis flavor fields (evidence, confidence) stay false.
  is_axis boolean not null default false,
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table public.shop_attributes (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.shops (id) on delete cascade,
  attribute_key text not null,
  value_json jsonb,
  value_text text,
  value_num double precision,
  confidence text,
  source_urls jsonb not null default '[]'::jsonb,
  status text not null default 'ok',
  collected_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (shop_id, attribute_key)
);

create table public.reviews (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.shops (id) on delete cascade,
  summary text not null,
  sentiment text,
  rating numeric,
  -- Month-precision dates such as '2026-10' are valid. Do not use date.
  review_date text,
  source_name text,
  source_url text,
  collected_at timestamptz,
  machine_translated boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.menu_items (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.shops (id) on delete cascade,
  item_name text not null,
  price_yen integer,
  note text,
  source_url text,
  collected_at timestamptz,
  extra_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.events (
  id bigint generated by default as identity primary key,
  event_uid text unique,
  shop_id bigint references public.shops (id) on delete set null,
  type text not null,
  title text not null,
  status text not null,
  -- Instants. The reader prints Asia/Tokyo wall time. all_day drops the clock.
  all_day boolean not null default false,
  starts_at timestamptz,
  ends_at timestamptz,
  date_text text,
  recurrence text,
  venue_name text,
  venue_address text,
  venue_ward text,
  venue_lat double precision,
  venue_lng double precision,
  organizer text,
  fee_text text,
  description text,
  booking_url text,
  confidence text,
  last_verified date,
  source_urls jsonb not null default '[]'::jsonb,
  extra_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index shops_uid_idx on public.shops (uid) where uid is not null;
create index shops_region_key_idx on public.shops (region_key);
create index shops_status_idx on public.shops (status);
create index shops_ward_idx on public.shops (ward);
create index shop_attributes_key_idx on public.shop_attributes (attribute_key);
create index reviews_shop_date_idx on public.reviews (shop_id, review_date desc);
create index menu_items_shop_idx on public.menu_items (shop_id);
create index events_status_starts_idx on public.events (status, starts_at);
create index events_shop_idx on public.events (shop_id);
create index attribute_definitions_category_idx on public.attribute_definitions (category, display_order);

alter table public.shops enable row level security;

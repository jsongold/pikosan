-- Café Index Tokyo catalog.
-- Extensible like the source catalog: identity lives on shops; every other
-- fact is an EAV row in shop_attributes (value jsonb + confidence + sources).
-- attribute_definitions holds labels and optional metadata (flavor axes use
-- category = 'flavor' and metadata.score_scale / allowed_values / atmos;
-- event type labels use category = 'event_type').
--
-- anon and authenticated may SELECT only. There are no write policies, and
-- insert/update/delete are revoked. service_role bypasses RLS — use that key
-- only as a server-side build secret, never as NEXT_PUBLIC_.

create table public.shops (
  id bigint generated by default as identity primary key,
  name text not null,
  name_kana text,
  prefecture text,
  ward text,
  address text,
  lat double precision,
  lng double precision,
  status text not null default 'active',
  source_urls jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint shops_lat_chk check (lat is null or (lat >= -90 and lat <= 90)),
  constraint shops_lng_chk check (lng is null or (lng >= -180 and lng <= 180))
);

create table public.attribute_definitions (
  key text primary key,
  label_ja text not null,
  category text,
  display_order integer not null default 999,
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table public.shop_attributes (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.shops (id) on delete cascade,
  attribute_key text not null,
  value_json jsonb,
  value_text text,
  value_num double precision,
  confidence text,
  source_urls jsonb not null default '[]'::jsonb,
  status text not null default 'ok',
  collected_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (shop_id, attribute_key)
);

create table public.reviews (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.shops (id) on delete cascade,
  summary text not null,
  sentiment text,
  rating numeric,
  review_date date,
  source_name text,
  source_url text,
  created_at timestamptz not null default now()
);

create table public.menu_items (
  id bigint generated by default as identity primary key,
  shop_id bigint not null references public.shops (id) on delete cascade,
  item_name text not null,
  price_yen integer,
  note text,
  source_url text,
  extra_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.events (
  id bigint generated by default as identity primary key,
  event_uid text unique,
  shop_id bigint references public.shops (id) on delete set null,
  type text not null,
  title text not null,
  status text not null,
  starts_at timestamptz,
  ends_at timestamptz,
  date_text text,
  recurrence text,
  venue_name text,
  venue_address text,
  venue_ward text,
  venue_lat double precision,
  venue_lng double precision,
  organizer text,
  fee_text text,
  description text,
  booking_url text,
  confidence text,
  last_verified date,
  source_urls jsonb not null default '[]'::jsonb,
  extra_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index shops_status_idx on public.shops (status);
create index shops_ward_idx on public.shops (ward);
create index shop_attributes_key_idx on public.shop_attributes (attribute_key);
create index reviews_shop_date_idx on public.reviews (shop_id, review_date desc);
create index menu_items_shop_idx on public.menu_items (shop_id);
create index events_status_starts_idx on public.events (status, starts_at);
create index events_shop_idx on public.events (shop_id);
create index attribute_definitions_category_idx on public.attribute_definitions (category, display_order);

alter table public.shops enable row level security;
alter table public.attribute_definitions enable row level security;
alter table public.shop_attributes enable row level security;
alter table public.reviews enable row level security;
alter table public.menu_items enable row level security;
alter table public.events enable row level security;

create policy catalog_select_shops on public.shops
  for select to anon, authenticated using (true);
create policy catalog_select_attribute_definitions on public.attribute_definitions
  for select to anon, authenticated using (true);
create policy catalog_select_shop_attributes on public.shop_attributes
  for select to anon, authenticated using (true);
create policy catalog_select_reviews on public.reviews
  for select to anon, authenticated using (true);
create policy catalog_select_menu_items on public.menu_items
  for select to anon, authenticated using (true);
create policy catalog_select_events on public.events
  for select to anon, authenticated using (true);

revoke insert, update, delete, truncate on public.shops from anon, authenticated;
revoke insert, update, delete, truncate on public.attribute_definitions from anon, authenticated;
revoke insert, update, delete, truncate on public.shop_attributes from anon, authenticated;
revoke insert, update, delete, truncate on public.reviews from anon, authenticated;
revoke insert, update, delete, truncate on public.menu_items from anon, authenticated;
revoke insert, update, delete, truncate on public.events from anon, authenticated;

grant select on public.shops to anon, authenticated;
grant select on public.attribute_definitions to anon, authenticated;
grant select on public.shop_attributes to anon, authenticated;
grant select on public.reviews to anon, authenticated;
grant select on public.menu_items to anon, authenticated;
grant select on public.events to anon, authenticated;

comment on table public.shops is 'Cafe identity. Status active is what the site publishes.';
comment on table public.shop_attributes is 'EAV facts. attribute_key is open-ended; label and axis metadata live on attribute_definitions.';
comment on table public.attribute_definitions is 'Labels plus optional metadata. category flavor = taste/atmosphere axis; category event_type = event type label.';
